#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES from the export manifest and checked-in licence texts.

No network, package metadata, or game data is read. Run with --check in release CI.
The component catalogue records provenance; the export manifest selects components.
"""
import argparse
import json
import re
import shlex
from pathlib import Path, PurePosixPath
import sys

ROOT = Path(__file__).resolve().parents[2]


def covers(name, path):
    return name.startswith(path) if path.endswith('/') else name == path


def linked_libraries(source):
    """Audit all branches of the small 3DS link declaration, without running CMake.

    Resolve find_library aliases and set/list(APPEND) link lists. Unknown variables
    fail closed; a new declaration form needs review instead of silently losing notices.
    """
    variables = {}
    required = {'gcc', 'c', 'sysbase', '3dsx_crt0'}  # implicit devkitARM runtime
    internal = {'render2d_shader_data', 'bench_scenes_data', 'drawskip_data', 'benchromfs_mount', 'swkbd_late'}
    commands = re.findall(r'\b(find_library|target_link_libraries|set|list)\s*\(([^()]*)\)',
                          re.sub(r'(?m)^\s*#.*$', '', source))
    for command, body in commands:
        words = shlex.split(body, comments=True)
        if command == 'find_library':
            variables.setdefault(words[0], set()).add(words[1])
            required.add(words[1])
        elif command == 'set' and words:
            variables.setdefault(words[0], set()).update(words[1:])
        elif command == 'list' and len(words) > 2 and words[0] == 'APPEND':
            variables.setdefault(words[1], set()).update(words[2:])
    def resolve(word, seen):
        if word in ('', 'PRIVATE', 'PUBLIC', 'INTERFACE') or word in internal:
            return set()
        if re.fullmatch(r'\$\{[A-Za-z_0-9]+\}', word):
            key = word[2:-1]
            if key in seen:
                return set()  # list = old list + additional libraries
            if key not in variables:
                raise ValueError('unresolved linked-library variable: ' + key)
            return set().union(*(resolve(v, seen | {key}) for v in variables[key]))
        return set(word.split(';')) - {''}
    for command, body in commands:
        if command == 'target_link_libraries':
            words = shlex.split(body, comments=True)
            for word in words[1:]:
                required.update(resolve(word, set()))
    return required


def local(root, name):
    path = PurePosixPath(name)
    if path.is_absolute() or '\\' in name or any(p in ('', '.', '..') for p in name.split('/')):
        raise ValueError('unsafe source path: ' + name)
    result = (root / name).resolve()
    if not result.is_relative_to(root.resolve()):
        raise ValueError('source outside tree: ' + name)
    return result


def generate(root, manifest, catalogue):
    names = [line.strip() for line in manifest.read_text(encoding='utf-8').splitlines()
             if line.strip() and not line.lstrip().startswith('#')]
    if len(set(n.casefold() for n in names)) != len(names):
        raise ValueError('duplicate manifest path')
    for name in names:
        if not local(root, name).is_file():
            raise ValueError('missing manifest source: ' + name)
    components = json.loads(catalogue.read_text(encoding='utf-8'))['components']
    selected = [c for c in components if any(any(covers(n, p) for p in c['paths']) for n in names)]
    for name in names:
        if name.startswith(('engine/vendor/', 'platform/3ds/vendor/')):
            if not any(any(covers(name, p) for p in c['paths']) for c in selected):
                raise ValueError('uncatalogued vendored source: ' + name)
    if 'platform/3ds/CMakeLists.txt' in names:
        required = linked_libraries(local(root, 'platform/3ds/CMakeLists.txt').read_text(encoding='utf-8'))
        documented = {library for c in selected for library in c.get('link_names', [])}
        if required - documented:
            raise ValueError('linked libraries without notices: ' + ', '.join(sorted(required - documented)))
    sections = ['THIRD-PARTY NOTICES\n'
                'Generated by tools/release/generate_notices.py; do not edit.\n'
                'Scope: UNDERTALE and DELTARUNE 3DS sources, linked runtime libraries and builder tools.\n'
                'The application and Butterscotch modifications are under AGPL-3.0; see LICENSE.\n'
                'Library texts below retain their own terms. No game content is included.\n']
    for component in selected:
        if not component.get('texts'):
            raise ValueError('component has no licence source: ' + component['name'])
        section = ['=' * 72, component['name'], 'Licence: ' + component['license'],
                   'Provenance: ' + component['provenance']]
        for source in component['texts']:
            name = source['file']
            if name not in names:
                raise ValueError('licence source absent from export manifest: ' + name)
            text = local(root, name).read_text(encoding='utf-8')
            if 'start' in source:
                if text.count(source['start']) != 1:
                    raise ValueError('licence start marker must occur once: ' + name)
                text = text[text.index(source['start']):]
            if 'end' in source:
                if source['end'] not in text:
                    raise ValueError('licence end marker missing: ' + name)
                text = text[:text.index(source['end'])]
            if not text.strip():
                raise ValueError('empty licence source: ' + name)
            section += ['Source: ' + name, '', text.rstrip()]
        sections.append('\n'.join(section) + '\n')
    return '\n'.join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', default='tools/release/manifest-ut.txt')
    parser.add_argument('--catalogue', default='tools/release/notices.json')
    parser.add_argument('--output', default='THIRD_PARTY_NOTICES')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        result = generate(ROOT, local(ROOT, args.manifest), local(ROOT, args.catalogue))
        output = local(ROOT, args.output)
        if args.check:
            if not output.exists() or output.read_text(encoding='utf-8') != result:
                raise ValueError('notices are stale; rerun generate_notices.py')
        else:
            output.write_text(result, encoding='utf-8', newline='\n')
        print('Notices verified' if args.check else 'Notices generated')
        return 0
    except (OSError, ValueError, KeyError) as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
