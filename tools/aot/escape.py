def _bind_classes():
    global InlineEmitter, Emitter

    class _Inline(G.Emitter):
        """R's bytecode as a C function over the C members (aoter_<k>_<code index>_<argc>)."""

        def __init__(self, dw, fn, k, spans, argc):
            G.Emitter.__init__(self, dw, fn, k)
            self.spans = spans or {}
            self.argc = argc

        def local(self, idx):
            if idx not in self.locals:
                self.locals[idx] = len(self.locals)
            self.vars[idx] = True
            return "aoteL_[%d]" % self.locals[idx]

        def fuse_constant(self, ins, d):
            sp = self.spans.get(ins.addr)
            if sp is None:
                return G.Emitter.fuse_constant(self, ins, d)
            e = self.emit
            data_pos = self.data_pos
            e("/* %s */" % " ".join("%04X" % x for x in sp.addrs))
            if sp.kind == "ret":
                e("goto aote_ok_;")
            elif sp.kind == "read":
                e("vmWeakCopyInto(&S[%d], &m[%d]);  /* argument0.%s */" % (d, data_pos[sp.member], sp.member))
            else:   # write: argument0.m = S[d - 1]
                pop = self.fn.instrs[sp.addrs[-1]]
                e("if (__builtin_expect(!aoteStoreMember(&m[%d], &S[%d], true, %d), 0)) goto aote_bail_;  /* argument0.%s = */"
                  % (data_pos[sp.member], d - 1, pop.t2, sp.member))
            return sp.addrs

        def gen_instr(self, ins, d, stack):
            k = _is_arg(self, ins)
            if k is not None:
                self.emit("/* %04X */" % ins.addr)
                if k < self.argc:
                    self.emit("vmWeakCopyInto(&S[%d], &A[%d]);  /* argument%d */" % (d, -k, k))
                else:
                    self.emit("S[%d] = RValue_makeUndefined();  /* argument%d (not passed) */" % (d, k))
                return
            if ins.op == G.OP_CALL:
                fname = self.dw.funcs[ins.extra]["name"]
                self.funcs[ins.extra] = True
                short = {"point_direction": "aotePointDirection00(ctx, S, %d, %d)" % (d, ins.extra),
                         "point_distance": "aotePointDistance00(S, %d)" % d}.get(fname)
                if short is not None and (ins.word & 0xFFFF) == 4:
                    self.emit("/* %04X */ if (!%s) {" % (ins.addr, short))
                    G.Emitter.gen_instr(self, ins, d, stack)
                    self.emit("}")
                    return
            G.Emitter.gen_instr(self, ins, d, stack)

    class _Esc(G.Emitter):
        """The function, with its sites' code around what gmlaot.py emits."""

        def __init__(self, dw, fn, k, sites):
            G.Emitter.__init__(self, dw, fn, k)
            self.sites = sites
            self.at_new = {s.addr: s for s in sites}
            self.at_r = {s.r_addr: s for s in sites if s.r_addr is not None}
            self.at_store = {s.store: s for s in sites}
            self.span_site = {}
            self.pinned = {}
            for s in sites:
                self.pinned[s.ci] = s.ctor_name
                if s.r_name:
                    self.pinned[s.r_ci] = s.r_name
            self.n_bindings = len(self.pinned)
            for s in sites:
                self.funcs[s.func] = True   # pins the constructor's FUNC name (aotMatches)
                for b, sp in s.spans.items():
                    self.span_site[b] = (s, sp)

        # The site's state: aoteS_<n> 0 (the generic code ran), 1 (in C), 2 (materialized); aoteW_<n> where the struct
        # would be: a stack index (from B), or -1 in the site's local.
        def fuse_constant(self, ins, d):
            hit = self.span_site.get(ins.addr)
            if hit is None:
                return G.Emitter.fuse_constant(self, ins, d)
            s, sp = hit
            n = s.n
            e = self.emit
            pos = s.data[sp.member]["pos"]
            e("/* escape %d: %s */" % (n, " ".join("%04X" % x for x in sp.addrs)))
            orig = [self.fn.instrs[x] for x in sp.addrs]
            if sp.kind == "read":
                e("if (aoteS_%d == 1) vmWeakCopyInto(&S[%d], &aoteM_%d[%d]);  /* %s.%s */" % (n, d, n, pos, s.local_name, sp.member))
                e("else {")
                for o in orig:
                    G.Emitter.gen_instr(self, o, self.fn.depth[o.addr], self.fn.stacks[o.addr])
                e("}")
                return sp.addrs
            # compound: struct, -9, dup, member read; the right-hand side; the write
            e("if (aoteS_%d == 1) vmWeakCopyInto(&S[%d], &aoteM_%d[%d]);  /* %s.%s */" % (n, d + 2, n, pos, s.local_name, sp.member))
            e("else {")
            for o in orig[:4]:
                G.Emitter.gen_instr(self, o, self.fn.depth[o.addr], self.fn.stacks[o.addr])
            e("}")
            for o in orig[4:-1]:
                G.Emitter.gen_instr(self, o, self.fn.depth[o.addr], self.fn.stacks[o.addr])
            pop = orig[-1]
            lv = self.local(s.local_idx)
            e("if (aoteS_%d == 1 && __builtin_expect(aoteStoreMember(&aoteM_%d[%d], &S[%d], false, %d), 1)) {"
              % (n, n, pos, d + 2, pop.t2))
            e("} else {")
            e("    if (aoteS_%d == 1) {" % n)
            e("        aoteMaterialize(ctx, &aoteR_%d, &aotec_%d_%d, aoteM_%d, aoteA_%d, %d, &%s, B + %d);"
              % (n, self.k, n, n, n, s.argc, lv, d + 3))
            e("        aoteS_%d = 2;" % n)
            e("        vmWeakCopyInto(&S[%d], &%s); AOT_SET_INT(&S[%d], -9, %d);" % (d, lv, d + 1, G.T_INT16))
            e("    }")
            G.Emitter.gen_instr(self, pop, self.fn.depth[pop.addr], self.fn.stacks[pop.addr])
            e("}")
            return sp.addrs

        def gen_instr(self, ins, d, stack):
            a = ins.addr
            e = self.emit
            if a in self.at_new:
                s = self.at_new[a]
                n = s.n
                guards = ["CTRPORT_AOT_ESCAPE",
                          "aoteBound(ctx, &aotec_%d, aoteb_%d, %d)" % (self.k, self.k, self.n_bindings),
                          "VM_codeIndexOfFuncName(ctx, %du) == %d" % (s.func, s.ci),
                          "aoteStatics(ctx, %d)" % s.ci,
                          "aoteNames(ctx, &aotec_%d_%d, &aoten_%d_%d)" % (self.k, n, self.k, n)]
                guards += ["vmIsPlainNumber(S[%d].type)" % (d - 2 - i) for i in range(s.argc)]
                e("/* %04X escape %d: new %s */" % (a, n, s.ctor_name))
                e("if (%s) {" % " && ".join(guards))
                e("    aoteR_%d = AOTE_RESERVE(ctx->runner, %d);" % (n, s.ci))
                for i in range(s.argc):
                    e("    aoteA_%d[%d] = S[%d];" % (n, i, d - 2 - i))
                for m in s.order:
                    dm = s.data[m]
                    j, kk = dm["pos"], dm["arg"]
                    if kk < s.argc:
                        e("    vmWeakCopyInto(&aoteM_%d[%d], &S[%d]); coerceIntStoreToRealInPlace(&aoteM_%d[%d], %d);  /* .%s = argument%d */"
                          % (n, j, d - 2 - kk, n, j, dm["t2"], m, kk))
                    else:
                        # the default: Pop.v.i of an int constant stores a real; the member gets a weak copy of it
                        e("    AOT_SET_REAL(&aoteM_%d[%d], (GMLReal) %d, GML_TYPE_VARIABLE); coerceIntStoreToRealInPlace(&aoteM_%d[%d], %d);  /* .%s = default */"
                          % (n, j, s.defaults[kk], n, j, dm["t2"], m))
                e("    S[%d] = RValue_makeUndefined();" % (d - s.n_args))
                e("    aoteS_%d = 1; aoteW_%d = %d;" % (n, n, d - s.n_args))
                e("    if (REACH_SHOULD_MATERIALIZE(ctx->runner)) {")
                e("        aoteMaterialize(ctx, &aoteR_%d, &aotec_%d_%d, aoteM_%d, aoteA_%d, %d, &S[%d], B + %d);"
                  % (n, self.k, n, n, n, s.argc, d - s.n_args, d - s.n_args + 1))
                e("        aoteS_%d = 2;" % n)
                e("    }")
                e("} else {")
                G.Emitter.gen_instr(self, ins, d, stack)
                e("}")
                return
            if a in self.at_r:
                s = self.at_r[a]
                n = s.n
                dd = s.r_d
                guards = ["aoteS_%d == 1" % n,
                          "aoteScript(ctx, %du, %d)" % (s.r_func, s.r_ci),
                          "VM_STACK_SIZE > B + %d" % (dd + s.r_depth + 2)]
                guards += ["vmIsPlainNumber(S[%d].type)" % (dd - 1 - i) for i in range(1, s.r_argc)]
                guards += ["ctx->funcCallCache[%d].builtin != nullptr" % f for f in s.r_builtins]
                e("/* %04X escape %d: %s inlined */" % (a, n, s.r_name))
                e("if (%s) {" % " && ".join(guards))
                e("    if (__builtin_expect(%s(ctx, B + %d, &S[%d], aoteM_%d, &S[%d]), 1)) {"
                  % (self.r_fn_name(s), dd, dd, n, dd - 1))
                e("        S[%d] = RValue_makeUndefined(); aoteW_%d = %d;" % (dd - s.r_argc, n, dd - s.r_argc))
                e("    } else {")
                e("        aoteMaterialize(ctx, &aoteR_%d, &aotec_%d_%d, aoteM_%d, aoteA_%d, %d, &S[%d], B + %d);"
                  % (n, self.k, n, n, n, s.argc, dd - 1, dd))
                e("        aoteS_%d = 2;" % n)
                e("        AOT_DEOPT(%d, 0x%X);" % (dd, a))
                e("    }")
                e("} else {")
                # A guard failed with the struct still in C: the script gets the real one (argument0 holds the
                # placeholder until now).
                e("    if (aoteS_%d == 1) {" % n)
                e("        aoteMaterialize(ctx, &aoteR_%d, &aotec_%d_%d, aoteM_%d, aoteA_%d, %d, &S[%d], B + %d);"
                  % (n, self.k, n, n, n, s.argc, dd - 1, dd))
                e("        aoteS_%d = 2;" % n)
                e("    }")
                G.Emitter.gen_instr(self, ins, d, stack)
                e("}")
                return
            if a in self.at_store:
                s = self.at_store[a]
                G.Emitter.gen_instr(self, ins, d, stack)
                e("if (aoteS_%d == 1) aoteW_%d = -1;  /* in %s */" % (s.n, s.n, s.local_name))
                return
            G.Emitter.gen_instr(self, ins, d, stack)

        def r_fn_name(self, s):
            return r_fn_name(self.k, s)

        def gen(self):
            body = G.Emitter.gen(self)
            pre = []
            for s in self.sites:
                n = s.n
                pre.append("    int32_t aoteS_%d = 0, aoteW_%d = 0; AoteRes aoteR_%d = { 0 }; RValue aoteM_%d[%d] = { 0 }; RValue aoteA_%d[%d] = { 0 };"
                           % (n, n, n, n, len(s.order), n, max(1, s.argc)))
                pre.append("    (void) aoteW_%d;" % n)
            pre += ["#pragma push_macro(\"AOT_DEOPT_AT\")",
                    "#undef AOT_DEOPT_AT",
                    "#define AOT_DEOPT_AT(ip) do { aotDeoptIp_ = (ip); goto aote_deopt_; } while (0)"]
            return pre + body

        def esc_tail(self):
            """After the function's other tail code: every struct still in C materializes where the generic code would
            hold it, then the deopt."""
            out = ["aote_deopt_: __attribute__((unused));"]
            for s in self.sites:
                n = s.n
                lv = self.local(s.local_idx)
                out.append("    if (aoteS_%d == 1) aoteMaterialize(ctx, &aoteR_%d, &aotec_%d_%d, aoteM_%d, aoteA_%d, %d, aoteW_%d >= 0 ? &S[aoteW_%d] : &%s, aoteW_%d >= 0 ? B + aoteW_%d + 1 : 0);"
                           % (n, n, self.k, n, n, n, s.argc, n, n, lv, n, n))
            out += ["    goto aot_deopt_;", "#pragma pop_macro(\"AOT_DEOPT_AT\")"]
            return out

        def prelude(self):
            """File-scope text before the function: the include, the constructors' members, the pinned code entries
            (the constructors and the inlined scripts) and the inlined scripts' functions."""
            k = self.k
            out = ["#include \"aot/vm_aot_escape.h\""]
            if os.environ.get("CTRPORT_AOT_ESCAPE") == "0":
                # The identity check of the generated code itself: every site compiled, every guard false.
                out = ["#define CTRPORT_AOT_ESCAPE 0"] + out
            for s in self.sites:
                out.append("static const AoteCtor aotec_%d_%d = { %d, { %s } };  /* %s: %s */"
                           % (k, s.n, len(s.order), ", ".join(str(s.data[m]["var"]) for m in s.order), s.ctor_name, ", ".join(s.order)))
                out.append("static uint32_t aoten_%d_%d;" % (k, s.n))
            out += _bindings(self.dw, k, self.pinned)
            done = set()
            for s in self.sites:
                if s.r_name is None or self.r_fn_name(s) in done:
                    continue
                done.add(self.r_fn_name(s))
                out += s.r_text
            return out

    InlineEmitter = _Inline
    Emitter = _Esc


def _bindings(dw, k, pinned):
    """The AotInlineBinding table pinning each code entry's bytecode and references (as typed.py's inline_bindings)."""
    out = ["static AotInlineCache aotec_%d;" % k]
    entries = []
    for ci, name in sorted(pinned.items()):
        e = dw.code_by_name[name]
        blob = bytes(dw.data[e["abs"]:e["abs"] + e["length"]])
        fn = G.Function(dw, e, blob)
        variables, functions = set(), set()
        for ins in fn.instrs.values():
            if ins.op in (G.OP_PUSHLOC, G.OP_PUSHGLB, G.OP_PUSHBLTN, G.OP_POP) or (ins.op == G.OP_PUSH and ins.t1 == G.T_VAR):
                variables.add(ins.var_index())
            if ins.op == G.OP_CALL:
                functions.add(ins.extra)
        prefix = "aoteb_%d_%d" % (k, ci)
        if variables:
            out.append("static const AotVarRef %s_v[] = {" % prefix)
            for idx in sorted(variables):
                v = dw.vars[idx]
                out.append("    { %d, %d, %d, %s }," % (idx, v["varID"], v["instanceType"], G.c_string(v["name"])))
            out.append("};")
        if functions:
            out.append("static const AotFuncRef %s_f[] = {" % prefix)
            for idx in sorted(functions):
                out.append("    { %d, %s }," % (idx, G.c_string(dw.funcs[idx]["name"])))
            out.append("};")
        digest = G.fnv1a64(blob[e["offset"]:e["length"]])
        entries.append("    { %d, %d, { %s, %d, %d, %d, 0x%016XULL, nullptr, %s, %d, %s, %d } },"
                       % (ci, dw.wad, G.c_string(name), e["offset"], e["length"], e["length"], digest,
                          prefix + "_v" if variables else "nullptr", len(variables),
                          prefix + "_f" if functions else "nullptr", len(functions)))
    out += ["static const AotInlineBinding aoteb_%d[] = {" % k] + entries + ["};"]
    return out


def r_fn_name(k, s):
    return "aoter_%d_%d_%d" % (k, s.r_ci, s.r_argc)


def _inline_function(dw, k, s):
    ie = InlineEmitter(dw, s.r_fn, k, s.r_spans, s.r_argc)
    ie.data_pos = {m: s.data[m]["pos"] for m in s.order}
    body = ie.gen()
    body, tail = ie.finish_refinds(body)
    tail = ie.stub_lines() + tail
    if tail or ie.cslots:
        raise G.Reject("internal: escape: %s needs slot lookups" % s.r_name)
    nl = len(ie.locals)
    nm = len(s.order)
    out = ["// %s inlined for escape elision: argument0's members are m[], argument i (i > 0) is A[-i]." % s.r_name,
           "static int %s(VMContext* ctx, const int32_t B, RValue* S, RValue* m, const RValue* A) {" % r_fn_name(k, s),
           "#pragma push_macro(\"AOT_DEOPT_AT\")",
           "#undef AOT_DEOPT_AT",
           "#define AOT_DEOPT_AT(ip) do { (void) (ip); goto aote_bail_; } while (0)",
           "    __asm__(\"\" : \"+r\"(S));",
           "    const uint8_t* const BC = ctx->bytecodeBase;   /* only read by calls the guards rule out */",
           "    Variable* const V = ctx->dataWin->vari.variables;",
           "    const uint32_t ip_ = ctx->ip;   /* the calls below set it to the script's own offsets */",
           "    RValue snap_[%d];" % nm,
           "    for (int32_t i_ = 0; %d > i_; i_++) snap_[i_] = m[i_];" % nm]
    if nl:
        out.append("    RValue aoteL_[%d];" % nl)
        out.append("    for (int32_t i_ = 0; %d > i_; i_++) aoteL_[i_] = RValue_makeUndefined();" % nl)
    out.append("    (void) BC; (void) V; (void) A;")
    out += body
    free = ["    for (int32_t i_ = 0; %d > i_; i_++) RValue_free(&aoteL_[i_]);" % nl] if nl else []
    out += ["aote_ok_: __attribute__((unused));"] + free + ["    ctx->ip = ip_;", "    return 1;",
            "aote_bail_: __attribute__((unused));"] + free + ["    ctx->ip = ip_;",
            "    for (int32_t i_ = 0; %d > i_; i_++) m[i_] = snap_[i_];" % nm,
            "    ctx->stack.top = B;",
            "    return 0;",
            "#pragma pop_macro(\"AOT_DEOPT_AT\")",
            "}"]
    return out

