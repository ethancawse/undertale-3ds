"""Escape elision (G9 (b)): a `new C(...)` whose struct never leaves the generated function keeps its members in C.

gmlaot.py calls plan() for each function it generates (generate_function). For every @@NewGMLObject@@ call in the
function, plan() proves, from the bytecode alone, that the struct the call makes

- is made by a constructor of the simple shape (constructor_summary): argument defaults, a static block, data members
  set from its arguments and methods bound to self, nothing else;
- goes, straight from the call, either into one local or, first, as argument0 into a script (the "R" script) whose code
  does nothing with argument0 but read and write its data members and return it (script_summary; a vector-rotation script),
  and from the R call's result into one local;
- is then only ever read member by member from that local (`v.m`, a read span) or updated by `v.m op= e` (a compound
  span) with the data members the constructor makes, and that local is written nowhere else;
- and that the call isn't in a loop (so it runs at most once per call of the function).

When the proof holds, the function is generated by Emitter (below), which emits, around the code gmlaot.py would emit
anyway (which stays and runs whenever a guard fails):

- at the call: the guards (the inlined code is the pinned one, the constructor resolves to the pinned code entry and
  its statics exist, the arguments are plain numbers), then the struct's ID and registry slot taken as
  Runner_createStruct would (nextInstanceId moves exactly as before), its members set in C as the constructor would
  set them, and an undefined placeholder where the struct would be;
- at the R call: R's own bytecode compiled into a C function (InlineEmitter) over the C members; any doubt in it
  restores the members, materializes the struct and lets the interpreter make the call;
- at each span: the member read or written in C.

Every way out to the interpreter first materializes every struct still in C (aoteMaterialize, engine/src/
vm_aot_escape.c) into the slot or local where the generic code would hold it. Whatever the proof doesn't cover is
reported (report lines "escape ...") and left as it was. engine/src/aot/vm_aot_escape.h has the run-time side.

UNDERTALE (WAD 16) has no constructors: plan() returns None for it at once, and its generated code doesn't change.
"""
import os
import struct

G = None   # the gmlaot module (bind)

MAX_MEMBERS = 4   # AOTE_MAX_MEMBERS
MAX_ARGS = 4      # AOTE_MAX_ARGS
MAX_SITES = 8
CMP_EQ = 3
# Builtin-named data members a struct keeps as plain members (tryPopStructMember: VMBuiltins_isInstanceScopedBuiltinVar),
# each checked to be stored and read that way: only these.
BUILTIN_MEMBERS = ("x", "y")
# Builtins an inlined R script may call: pure math, so that a bail (which lets the interpreter make the whole call
# again) repeats nothing that shows. point_direction and point_distance have their (0, 0, x, +0) shortcuts.
R_BUILTINS_EXTRA = ("point_direction", "point_distance")


def bind(mod):
    global G
    G = mod
    _bind_classes()


class NotElided(Exception):
    pass


def _var(dw, ins):
    return dw.vars[ins.var_index()]


def _is_arg(em, ins, n=None):
    """Whether ins pushes argumentn (any n when n is None); returns the number or None."""
    if ins.op == G.OP_PUSH and ins.t1 == G.T_VAR and ins.var_type() == G.VT_NORMAL and ins.inst == G.ARG:
        k = em.arg_number(_var(em.dw, ins))
    elif ins.op == G.OP_PUSHBLTN and ins.var_type() == G.VT_NORMAL and ins.inst == G.SELF:
        k = em.arg_number(_var(em.dw, ins))
    else:
        return None
    if k is None or (n is not None and k != n):
        return None
    return k


def _is_local_read(dw, ins):
    if ins.op == G.OP_PUSHLOC or (ins.op == G.OP_PUSH and ins.t1 == G.T_VAR and ins.inst == G.LOCAL):
        return True
    return False


def _member_var(dw, ins, data):
    """The data member (name) a [stacktop] access names, when it is one of data's; else None."""
    v = _var(dw, ins)
    if v["name"] not in data:
        return None
    want = data[v["name"]]
    if v["varID"] == G.VARIABLE_BUILTIN:
        if v["name"] not in BUILTIN_MEMBERS or want["varID"] != G.VARIABLE_BUILTIN:
            return None
    elif v["varID"] < 0 or v["varID"] != want["varID"]:
        return None
    return v["name"]


def _plain_dup(fn, ins):
    """A Dup that copies the two slots below it (the struct and the -9 of `v.m op= e`)."""
    if ins.op != G.OP_DUP or (ins.word & 0xFFFFF800) == 0x86058800 or ins.addr in fn.fused_targets:
        return False
    return fn.dup_slots.get(ins.addr) == 2


def _stacktop_push(ins):
    return ins.op == G.OP_PUSH and ins.t1 == G.T_VAR and ins.var_type() == G.VT_STACKTOP


def _stacktop_pop(ins, simple):
    if ins.op != G.OP_POP or ins.var_type() != G.VT_STACKTOP:
        return False
    return (ins.t1 == G.T_VAR) == simple


def _pushi(ins, k):
    return ins.op == G.OP_PUSHI and ins.inst == k


# ---[ The constructor ]---

def constructor_summary(dw, ci_name):
    """(data, methods, defaults) for a constructor of the simple shape, else raises NotElided:
    data: name -> {"pos", "arg", "t2", "var", "varID"} for each member set from an argument (in the constructor's order);
    methods: the names of the members set to methods bound to self; defaults: arg -> the int constant its default
    pushes when the argument is undefined (stored as a real: Pop.v.i to the argument)."""
    entry = dw.code_by_name.get(ci_name)
    if entry is None:
        raise NotElided("no code entry %s" % ci_name)
    blob = bytes(dw.data[entry["abs"]:entry["abs"] + entry["length"]])
    fn = G.Function(dw, entry, blob)
    if fn.stubs:
        raise NotElided("the constructor has instructions left to the interpreter")

    class A:   # arg_number needs an emitter's view of DIRECT
        pass
    em = A()
    em.dw = dw
    em.arg_number = lambda v: G.Emitter.arg_number(em, v)
    data, methods, defaults, order = {}, [], {}, []
    a = entry["offset"]
    seen = set()
    statics = False

    def ins_at(x):
        if x not in fn.instrs or x not in fn.depth:
            raise NotElided("constructor: no instruction at %04X" % x)
        return fn.instrs[x]

    while True:
        if a in seen:
            raise NotElided("constructor: a loop")
        seen.add(a)
        ins = ins_at(a)
        if ins.op == G.OP_EXIT and fn.depth[a] == 0:
            break
        if ins.op == G.OP_B and ins.target() > a:
            a = ins.target()
            continue
        k = _is_arg(em, ins)
        if k is not None and not statics and not data:
            # argument default: push argk; pushbltn undefined; cmp eq; bf L; pushi K; pop.v.i argk; L:
            i1, i2 = ins_at(ins.next), None
            i2 = ins_at(i1.next)
            i3 = ins_at(i2.next)
            if (i1.op == G.OP_PUSHBLTN and _var(dw, i1)["name"] == "undefined" and i2.op == G.OP_CMP
                    and ((i2.word >> 8) & 0xFF) == CMP_EQ and i3.op == G.OP_BF):
                i4 = ins_at(i3.next)
                i5 = ins_at(i4.next)
                if (i4.op == G.OP_PUSHI and i5.op == G.OP_POP and i5.t1 == G.T_VAR and i5.t2 in (G.T_INT32, G.T_INT16, G.T_INT64)
                        and i5.var_type() == G.VT_NORMAL and em.arg_number(_var(dw, i5)) == k and i3.target() == i5.next
                        and k not in defaults):
                    defaults[k] = i4.inst
                    a = i5.next
                    continue
                raise NotElided("constructor: argument%d's default isn't an int constant" % k)
        if ins.op == G.OP_BREAK and ins.inst == -6 and not statics and not data:
            # if (!isstaticok) { statics }; setstatic. With the statics there (a guard), only the flag is read.
            bt = ins_at(ins.next)
            if bt.op != G.OP_BT:
                raise NotElided("constructor: isstaticok without a branch")
            end = ins_at(bt.target())
            if end.op != G.OP_BREAK or end.inst != -7:
                raise NotElided("constructor: the static block doesn't end in setstatic")
            statics = True
            a = end.next
            continue
        if k is not None:
            p = ins_at(ins.next)
            if p.op == G.OP_POP and p.t1 == G.T_VAR and p.var_type() == G.VT_NORMAL and p.inst == G.SELF:
                v = _var(dw, p)
                if v["name"] in data or v["name"] in methods:
                    raise NotElided("constructor: member %s set twice" % v["name"])
                if v["varID"] == G.VARIABLE_BUILTIN and v["name"] not in BUILTIN_MEMBERS:
                    raise NotElided("constructor: builtin-named member %s" % v["name"])
                if v["varID"] < 0 and v["varID"] != G.VARIABLE_BUILTIN:
                    raise NotElided("constructor: member %s has no varID" % v["name"])
                data[v["name"]] = {"pos": len(data), "arg": k, "t2": p.t2, "var": p.var_index(), "varID": v["varID"]}
                order.append(v["name"])
                a = p.next
                continue
            raise NotElided("constructor: argument%d goes somewhere else" % k)
        # method member: push.i F; conv; pushi -1; conv; call method argc 2; pop.v.v self.m
        if ins.op == G.OP_PUSH and ins.t1 == G.T_INT32:
            seq = [ins]
            x = ins.next
            for _ in range(5):
                seq.append(ins_at(x))
                x = seq[-1].next
            c1, p1, c2, call, p = seq[1:]
            if (c1.op == G.OP_CONV and _pushi(p1, -1) and c2.op == G.OP_CONV and call.op == G.OP_CALL
                    and dw.funcs[call.extra]["name"] == "method" and (call.word & 0xFFFF) == 2
                    and p.op == G.OP_POP and p.t1 == G.T_VAR and p.var_type() == G.VT_NORMAL and p.inst == G.SELF):
                v = _var(dw, p)
                if v["name"] in data or v["name"] in methods:
                    raise NotElided("constructor: member %s set twice" % v["name"])
                methods.append(v["name"])
                a = p.next
                continue
        raise NotElided("constructor: instruction %02X at %04X" % (ins.op, a))
    if not data:
        raise NotElided("constructor: no data member")
    if len(data) > MAX_MEMBERS:
        raise NotElided("constructor: %d data members" % len(data))
    return data, methods, defaults


# ---[ Spans ]---

class Span:
    """A run of instructions emitted as one: kind "read" (v.m), "compound" (v.m op= e), "write" (R: argument0.m = e),
    "ret" (R: return argument0)."""

    def __init__(self, kind, addrs, member, d0, last=None):
        self.kind, self.addrs, self.member, self.d0, self.last = kind, addrs, member, d0, last


def _span_at(em, fn, a, data, is_struct_push, allow_ret):
    """The span starting with the struct push at a, else raises NotElided."""
    dw = fn.dw
    ins = fn.instrs[a]
    if not is_struct_push(ins):
        raise NotElided("internal: no struct push at %04X" % a)
    d0 = fn.depth[a]
    n1 = fn.instrs.get(ins.next)

    def plain(x):
        if x not in fn.instrs or x not in fn.depth:
            raise NotElided("span at %04X runs into %04X" % (a, x))
        if x in fn.labels:
            raise NotElided("a label inside the span at %04X" % a)
        if x in fn.stubs:
            raise NotElided("a stub inside the span at %04X" % a)
        return fn.instrs[x]

    if a in fn.stubs:
        raise NotElided("a stub at %04X" % a)
    if allow_ret and n1 is not None and n1.op == G.OP_RET:
        plain(ins.next)
        return Span("ret", [a, ins.next], None, d0)
    n1 = plain(ins.next)
    if not _pushi(n1, -9):
        raise NotElided("the struct at %04X isn't used as v.m" % a)
    n2 = plain(n1.next)
    if _stacktop_push(n2):
        m = _member_var(dw, n2, data)
        if m is None:
            raise NotElided("%04X reads .%s, not a data member" % (n2.addr, _var(dw, n2)["name"]))
        return Span("read", [a, n1.addr, n2.addr], m, d0)
    if allow_ret and _stacktop_pop(n2, True):
        m = _member_var(dw, n2, data)
        if m is None:
            raise NotElided("%04X writes .%s, not a data member" % (n2.addr, _var(dw, n2)["name"]))
        return Span("write", [a, n1.addr, n2.addr], m, d0)
    if not allow_ret and _plain_dup(fn, n2):
        n3 = plain(n2.next)
        if not _stacktop_push(n3):
            raise NotElided("the Dup at %04X isn't v.m op= e" % n2.addr)
        m = _member_var(dw, n3, data)
        if m is None:
            raise NotElided("%04X reads .%s, not a data member" % (n3.addr, _var(dw, n3)["name"]))
        addrs = [a, n1.addr, n2.addr, n3.addr]
        x = n3.next
        while True:
            ins_x = plain(x)
            if _stacktop_pop(ins_x, False):
                if _member_var(dw, ins_x, data) != m or fn.depth[x] != d0 + 3:
                    raise NotElided("the compound write at %04X isn't to .%s" % (x, m))
                addrs.append(x)
                return Span("compound", addrs, m, d0, addrs[4:-1])
            if not _inner_ok(em, fn, ins_x, d0):
                raise NotElided("instruction %02X at %04X inside v.%s op= e" % (ins_x.op, x, m))
            addrs.append(x)
            x = ins_x.next
    raise NotElided("the struct at %04X isn't used as v.m" % a)


def _inner_ok(em, fn, ins, d0):
    """The right-hand side of v.m op= e: instructions whose generated code never leaves for the interpreter (no
    AOT_CHECK, no site), and which stay above the struct and the -9."""
    if fn.depth[ins.addr] < d0 + 3 or fn.after[ins.addr] < d0 + 3:
        return False
    if ins.op in (G.OP_PUSHI, G.OP_CONV, G.OP_ADD, G.OP_SUB, G.OP_MUL):
        return True
    if ins.op == G.OP_PUSH and ins.t1 in (G.T_INT16, G.T_INT32, G.T_DOUBLE):
        return True
    if ins.op == G.OP_PUSHLOC and ins.var_type() == G.VT_NORMAL:
        return True
    if _is_arg(em, ins) is not None and G.DIRECT:
        return True
    return False


# ---[ The R script ]---

def script_summary(em, name, argc, data):
    """(fn, spans, max depth, builtin func indices) for a script whose argument0 is only read and written member by
    member and returned, else raises NotElided."""
    dw = em.dw
    entry = dw.code_by_name.get(name)
    if entry is None:
        raise NotElided("no code entry %s" % name)
    blob = bytes(dw.data[entry["abs"]:entry["abs"] + entry["length"]])
    fn = G.Function(dw, entry, blob)
    if fn.stubs:
        raise NotElided("%s has instructions left to the interpreter" % name)
    ie = InlineEmitter(dw, fn, em.k, None, argc)
    spans, covered = {}, set()
    for a in _addrs(fn):
        ins = fn.instrs[a]
        if _is_arg(ie, ins, 0) is not None:
            sp = _span_at(ie, fn, a, data, lambda i: _is_arg(ie, i, 0) is not None, True)
            spans[a] = sp
            covered.update(sp.addrs[1:])
    builtins = set()
    inline = G.inline_math() if G.INLINE else {}
    for a in _addrs(fn):
        if a in covered or a in spans:
            continue
        ins = fn.instrs[a]
        op = ins.op
        if op in (G.OP_PUSHI, G.OP_CONV, G.OP_POPZ, G.OP_B, G.OP_BT, G.OP_BF, G.OP_NEG, G.OP_NOT) or op in G.BINARY:
            continue
        if op == G.OP_PUSH and ins.t1 in (G.T_INT16, G.T_INT32, G.T_DOUBLE):
            continue
        if _is_arg(ie, ins) is not None and G.DIRECT:
            continue
        if _is_local_read(dw, ins) and ins.var_type() == G.VT_NORMAL and _var(dw, ins)["varID"] >= 0:
            continue
        if (op == G.OP_POP and ins.t1 == G.T_VAR and ins.var_type() == G.VT_NORMAL and ins.inst == G.LOCAL
                and _var(dw, ins)["varID"] >= 0):
            continue
        if op == G.OP_CALL:
            fname = dw.funcs[ins.extra]["name"]
            if fname in dw.code_by_name or ("gml_Script_" + fname) in dw.code_by_name:
                raise NotElided("%s calls the script %s" % (name, fname))
            if G.builtin_audit().get(fname, 0) is not None or (fname not in inline and fname not in R_BUILTINS_EXTRA):
                raise NotElided("%s calls %s" % (name, fname))
            builtins.add(ins.extra)
            continue
        raise NotElided("%s: instruction %02X at %04X" % (name, op, a))
    for a, ins in fn.instrs.items():
        if a in fn.depth and (ins.op == G.OP_EXIT or (ins.next == len(fn.blob) and ins.op not in (G.OP_RET, G.OP_B))):
            raise NotElided("%s can leave without returning argument0" % name)
        if a in fn.depth and ins.op == G.OP_RET and a not in covered:
            raise NotElided("%s returns something other than argument0" % name)
    if len(blob) in fn.labels:
        raise NotElided("%s branches to its end" % name)
    return fn, spans, max(fn.depth.values()) + 1, sorted(builtins)


# ---[ The function's sites ]---

class Site:
    pass


def _loops_back(fn, start):
    """Whether the instruction at start can run again after itself in one call."""
    seen = set()
    work = [s for s in fn.successors(fn.instrs[start])]
    while work:
        x = work.pop()
        if x == start:
            return True
        if x in seen or x not in fn.instrs or x not in fn.depth:
            continue
        seen.add(x)
        ins = fn.instrs[x]
        if ins.op in (G.OP_RET, G.OP_EXIT):
            continue
        work.extend(fn.successors(ins))
    return False


def _addrs(fn):
    """The function's reachable instructions, in order (fn.depth also has the end of the code)."""
    return [a for a in sorted(fn.depth) if a in fn.instrs]


def find_sites(em, name, report):
    """The provable sites of the function (Site objects), reporting every `new` in it."""
    dw, fn = em.dw, em.fn
    news = [a for a in _addrs(fn) if fn.instrs[a].op == G.OP_CALL
            and dw.funcs[fn.instrs[a].extra]["name"] == "@@NewGMLObject@@"]
    if not news:
        return []
    sites, used_locals = [], {}
    for a in news:
        try:
            if em.typed:
                raise NotElided("the function has typed regions")
            if len(sites) >= MAX_SITES:
                raise NotElided("more than %d sites" % MAX_SITES)
            sites.append(_prove_site(em, a, used_locals))
            s = sites[-1]
            report.append("escape %s @%04X: new %s elided%s (members %s; %d reads, %d updates)"
                          % (name, a, s.ctor_name, (", %s inlined" % s.r_name) if s.r_name else "", ",".join(s.order),
                             sum(1 for sp in s.spans.values() if sp.kind == "read"),
                             sum(1 for sp in s.spans.values() if sp.kind == "compound")))
        except (NotElided, G.Reject) as ex:
            report.append("escape %s @%04X: new kept: %s" % (name, a, ex))
        except Exception as ex:  # fail closed: a generator bug keeps the site generic, and says so
            report.append("escape %s @%04X: new kept: internal error %s: %s" % (name, a, type(ex).__name__, ex))
    for i, s in enumerate(sites):
        s.n = i + 1
    return sites


def _prove_site(em, a, used_locals):
    dw, fn = em.dw, em.fn
    ins = fn.instrs[a]
    d = fn.depth[a]
    n = ins.word & 0xFFFF
    if n < 1 or n - 1 > MAX_ARGS:
        raise NotElided("%d arguments" % n)
    if a in fn.stubs:
        raise NotElided("left to the interpreter")
    # push.i K; conv.i.v; call: argument0 of @@NewGMLObject@@ is FUNC index K, an int32 (not a method)
    prev = {i.next: i for x, i in fn.instrs.items() if x in fn.depth}
    conv = prev.get(a)
    push = prev.get(conv.addr) if conv is not None else None
    top = None
    if (conv is not None and push is not None and conv.op == G.OP_CONV and conv.t1 == G.T_INT32 and conv.t2 == G.T_VAR
            and a not in fn.labels and conv.addr not in fn.labels and conv.addr not in fn.stubs and push.addr not in fn.stubs):
        if push.op == G.OP_PUSH and push.t1 == G.T_INT32:
            top = struct.unpack("<i", struct.pack("<I", push.extra))[0]
        elif push.op == G.OP_PUSHI or (push.op == G.OP_PUSH and push.t1 == G.T_INT16):
            top = push.inst
    if top is None or not (0 <= top < len(dw.funcs)):
        raise NotElided("the constructor isn't a constant function index")
    s = Site()
    s.addr, s.d, s.n_args, s.func = a, d, n, top
    s.ctor_name = dw.funcs[top]["name"]
    ci_entry = dw.code_by_name.get(s.ctor_name)
    if ci_entry is None:
        raise NotElided("%s has no code entry" % s.ctor_name)
    s.ci = ci_entry["index"]
    s.data, s.methods, s.defaults = constructor_summary(dw, s.ctor_name)
    s.order = sorted(s.data, key=lambda m: s.data[m]["pos"])
    s.argc = n - 1
    for m in s.order:
        k = s.data[m]["arg"]
        if k >= s.argc and k not in s.defaults:
            raise NotElided("member %s would be undefined (argument%d not passed, no default)" % (m, k))
    if _loops_back(fn, a):
        raise NotElided("in a loop")
    # new -> (R ->) store
    x = ins.next
    if x in fn.labels or x not in fn.depth:
        raise NotElided("a label after the call")
    nxt = fn.instrs[x]
    s.r_addr, s.r_name = None, None
    if nxt.op == G.OP_CALL:
        m = nxt.word & 0xFFFF
        fname = dw.funcs[nxt.extra]["name"]
        if not em.script_callee(nxt.extra) or fname not in dw.code_by_name:
            raise NotElided("the struct goes to %s" % fname)
        if m < 1 or fn.depth[x] != d - n + 1 or m - 1 > MAX_ARGS:
            raise NotElided("the struct isn't argument0 of %s" % fname)
        s.r_addr, s.r_name, s.r_func, s.r_argc, s.r_d = x, fname, nxt.extra, m, fn.depth[x]
        s.r_ci = dw.code_by_name[fname]["index"]
        s.r_fn, s.r_spans, s.r_depth, s.r_builtins = script_summary(em, fname, m, s.data)
        s.order = sorted(s.data, key=lambda mm: s.data[mm]["pos"])
        try:
            s.r_text = _inline_function(dw, em.k, s)
        except G.Reject as ex:
            raise NotElided("%s: %s" % (fname, ex))
        x = nxt.next
        if x in fn.labels or x not in fn.depth:
            raise NotElided("a label after the %s call" % fname)
        nxt = fn.instrs[x]
    if not (nxt.op == G.OP_POP and nxt.t1 == G.T_VAR and nxt.var_type() == G.VT_NORMAL and nxt.inst == G.LOCAL
            and _var(dw, nxt)["varID"] >= 0 and x not in fn.stubs):
        raise NotElided("the struct isn't stored in a local")
    s.store, s.store_d, s.local_idx = x, fn.depth[x], nxt.var_index()
    s.local_name = _var(dw, nxt)["name"]
    s.local_var_id = _var(dw, nxt)["varID"]
    if s.local_name in used_locals:
        raise NotElided("local %s holds another site's struct" % s.local_name)
    # Every access of the local: the one store, and spans.
    s.spans = {}
    for b, ib in local_accesses(dw, fn, s.local_name, s.local_var_id, s.local_idx, s.store):
        s.spans[b] = _span_at(em, fn, b, s.data, lambda i, nm=s.local_name: _is_local_read(dw, i) and _var(dw, i)["name"] == nm
                              and i.var_type() == G.VT_NORMAL, False)
    used_locals[s.local_name] = True
    return s


def _var_refs(fn):
    """(address, instruction) of every reachable instruction that names a variable."""
    for b in _addrs(fn):
        ib = fn.instrs[b]
        if ib.extra is None:
            continue
        if ib.op in (G.OP_PUSHLOC, G.OP_PUSHGLB, G.OP_PUSHBLTN, G.OP_POP) or (ib.op == G.OP_PUSH and ib.t1 == G.T_VAR):
            yield b, ib


def local_accesses(dw, fn, name, var_id, idx, store):
    """The reads of the local (the instructions that start them), else NotElided: anything naming the variable (by
    name in any scope, or its varID as a local) that isn't the one store or a plain read of this VARI entry. A name
    match in another scope is only let through as a plain (VT_NORMAL) access whose instance type isn't local."""
    reads = []
    for b, ib in _var_refs(fn):
        v = _var(dw, ib)
        local = ib.op == G.OP_PUSHLOC or ib.inst == G.LOCAL or v["instanceType"] == G.LOCAL
        if v["name"] != name and not (local and v["varID"] == var_id):
            continue
        if ib.var_type() != G.VT_NORMAL:
            raise NotElided("%s is accessed as an array (or through the stack) at %04X" % (name, b))
        if not local:
            continue
        if ib.var_index() != idx:
            raise NotElided("local %s has another VARI entry at %04X" % (name, b))
        if b in fn.stubs:
            raise NotElided("local %s is accessed by the interpreter at %04X" % (name, b))
        if ib.op == G.OP_POP:
            if b != store:
                raise NotElided("local %s is written at %04X too" % (name, b))
            continue
        reads.append((b, ib))
    return reads


def plan(dw, fn, k, name, em, report):
    """An Emitter for the function when it has a provable site, else None (the function is generated as before).
    Reports every `new` in the function."""
    if dw.wad < 17 or not G.DIRECT:
        return None
    sites = find_sites(em, name, report)
    if not sites:
        return None
    esc = Emitter(dw, fn, k, sites)
    esc.typed, esc.typed_exits = em.typed, em.typed_exits
    return esc


